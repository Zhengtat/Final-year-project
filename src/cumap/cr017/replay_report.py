"""CR-017 STOP 4: render reports/cr017/historical_replay.md from headline_metrics.json (machine-readable output is the source of truth)."""
# ruff: noqa: ISC004

from __future__ import annotations

import json
from pathlib import Path

OUT = Path("reports/cr017")


def _v(x: dict, k: str = "f1") -> str:
    if x.get("status") == "NOT_EVALUABLE":
        return "NOT_EVALUABLE"
    v = x.get(k)
    return "n/a" if v is None else f"{v:.3f}"


def main() -> None:
    d = json.loads((OUT / "headline_metrics.json").read_text())
    m = d["meta"]
    L = [
        "# CR-017 STOP 4 — historical replay of the five-metric evaluator",
        "",
        f"Scorer `{m['scorer_version']}`; model calls: **{m['model_calls']}**; frozen artefacts hashed before/after: "
        f"**{m['frozen_artifacts_hashed']}**, changed: **{len(m['frozen_artifacts_changed'])}**.",
        "",
        "Source: `headline_metrics.json` (generated by `cumap.cr017.replay`). Intervals are section-bootstrap and "
        "descriptive only (7 sections < 10 units); no composite score.",
        "",
        "## P&D-E2E held-out (7 sections, headline population)",
        "",
        "| Level | Concept F1 | Ancestor Hierarchy F1 | Pair Recall | Relation Macro F1 ⚠ | Strict E2E Edge F1 | = frozen CR-012 |",
        "|---|---|---|---|---|---|---|",
    ]
    for lv, r in d["pd"]["heldout"].items():
        h, c = r["headline"], r["frozen_compat"]
        L.append(
            f"| {lv} | {_v(h['concept_f1'])} | {_v(h['ancestor_hierarchy_f1'])} | {_v(h['pair_recall'], 'recall')} | "
            f"{_v(h['relation_macro_f1'])} | {_v(h['strict_e2e_edge_f1'])} | {all(x['match'] for x in c.values())} |"
        )
    L += [
        "",
        "⚠ Relation Macro F1 is a headline metric but is computed over few gold edges per class; classes with support ≤3 are "
        "flagged low-support in `diagnostics.json` and the value must be read with its per-class support table.",
        "",
        "## P&D-E2E pilot (development, not a headline population)",
        "",
        "Only 1.5 has runs at E1–E4 (2.6 has E0/E3/E4 runs but none that score at E1–E4 here); 1.5 has no hierarchy gold, "
        "so hierarchy is NOT_EVALUABLE (no pseudo-gold).",
        "",
        "| Level | Sections | Concept F1 | Ancestor Hierarchy F1 | Pair Recall | Relation Macro F1 ⚠ | Strict E2E Edge F1 |",
        "|---|---|---|---|---|---|---|",
    ]
    for lv, r in d["pd"]["pilot"].items():
        h = r["headline"]
        L.append(
            f"| {lv} | {', '.join(r['sections'])} | {_v(h['concept_f1'])} | {_v(h['ancestor_hierarchy_f1'])} | "
            f"{_v(h['pair_recall'], 'recall')} | {_v(h['relation_macro_f1'])} | {_v(h['strict_e2e_edge_f1'])} |"
        )
    L += [
        "",
        "## SciNLP held-out (3 documents; separate benchmark, never pooled with P&D)",
        "",
        "Mention-level gold with no identity gold: the P&D metric definitions do not transfer one-to-one. "
        "Concept and Pair Recall are reported as **mention-level analogues**; hierarchy is NOT_EVALUABLE; "
        "Relation Macro F1 is NOT_COMPUTED. 3 documents → `NOT_EVALUABLE_SMALL_N` (no interval).",
        "",
        "| Level | Entity strict F1 (concept analogue) | Hierarchy | Pair Recall (analogue) | Relation Macro F1 | Relation strict F1 | = frozen |",
        "|---|---|---|---|---|---|---|",
    ]
    for lv, s in d["scinlp"].items():
        L.append(
            f"| {lv} | {_v(s['concept_f1'])} | NOT_EVALUABLE (no identity gold) | {_v(s['pair_recall'], 'recall')} | "
            f"NOT_COMPUTED | {_v(s['strict_e2e_edge_f1'])} | {all(s['frozen_check'].values())} |"
        )
    L += [
        "",
        "## Open item for Research",
        "",
        "**RESEARCH DECISION REQUIRED (SciNLP):** should SciNLP Relation Macro F1 be defined at mention level (needs per-class "
        "classifier outcomes, which the frozen scorer does not retain) or stay NOT_EVALUABLE? Nothing was chosen silently.",
        "",
    ]
    (OUT / "historical_replay.md").write_text("\n".join(L))


if __name__ == "__main__":
    main()
