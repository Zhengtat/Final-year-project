"""CR-040 ($0, no model call, changes no config): render the owner review sheet for the six unreviewed registry v1.4 relations.

    uv run python -m cumap.cr040.review_sheet

Reads the CURRENT text from `configs/relations_v1.4.yaml` (never edited) and the PROPOSED text with its reasons from `docs/cr040/v14_wording_proposals.yaml`,
and writes `docs/cr040/v14_relation_review.md`, current text beside proposed text, one section per relation, with an owner checklist."""

from __future__ import annotations

import hashlib
from pathlib import Path

import yaml

from cumap.config import REPO_ROOT

V14 = REPO_ROOT / "configs/relations_v1.4.yaml"
PROPOSALS = REPO_ROOT / "docs/cr040/v14_wording_proposals.yaml"
OUT = REPO_ROOT / "docs/cr040/v14_relation_review.md"
ORDER = ("subtask_of", "enhanced_by", "similar_to", "measured_by", "evaluated_by", "evaluated_on")
FIELDS = ("definition", "template", "examples", "near_misses")


def _one(text: str | None) -> str:
    return " ".join((text or "").split())


def _cell(value) -> str:
    if isinstance(value, list):
        if value and isinstance(value[0], dict):
            return (
                "<br>".join(
                    f"not **{m['relation']}**: {_one(m['example'])} ({_one(m['why'])})"
                    for m in value
                )
                or "none"
            )
        return "<br>".join(f"- {_one(v)}" for v in value) or "none"
    return _one(value) or "none"


def _esc(s: str) -> str:
    return s.replace("|", "\\|")


def render(reg: dict, prop: dict, v14_sha: str) -> str:
    by = {r["name"]: r for r in reg["relations"]}
    L = [
        "# CR-040 draft: owner review of the six unreviewed registry v1.4 relations",
        "",
        (
            "Written for: the project owner. **Status: DRAFT for review. Nothing here is adopted.** `configs/relations_v1.4.yaml` was not edited "
            f"(sha256 `{v14_sha[:16]}`); v1.4 stays unadopted. Generated by `cumap.cr040.review_sheet` from `configs/relations_v1.4.yaml` (current text) "
            "and `docs/cr040/v14_wording_proposals.yaml` (proposed text and reasons). Adoption of any wording, and whether v1.4 is adopted at all, is the owner's decision "
            "(handoff section 3 item 4, and CR-022 Part B depends on it)."
        ),
        "",
        (
            "How to read it: each section puts the text now in v1.4 beside the proposed text, then gives the reason for each change. Mark the checklist at the end of "
            "each section: **accept**, **edit** (write the wording you want) or **reject** (keep the current text)."
        ),
        "",
        "## Cross-cutting points",
        "",
    ]
    for c in prop.get("cross_cutting", []):
        L += [f"- **{c['title']}.** {_one(c['text'])}"]
    L += ["", "## The six relations", ""]
    for name in ORDER:
        r, p = by[name], prop["relations"][name]
        L += [
            f"### {name}",
            "",
            (
                f"Family `{r['family']}`, layer `{r['layer']}`, directional {r['directional']}, symmetric {r['symmetric']}, transitive {r['transitive']}, "
                f"inverse `{r['inverse_of']}`, SciNLP label(s) `{', '.join((r.get('external_labels') or {}).get('SciNLP', []))}` (unchanged by this proposal)."
            ),
            "",
            "| field | current (v1.4) | proposed | reason |",
            "|---|---|---|---|",
        ]
        for f in FIELDS:
            cur, new = r.get(f), p.get(f)
            L.append(
                f"| {f} | {_esc(_cell(cur))} | {_esc(_cell(new)) if new != cur else '(unchanged)'} | {_esc(_one(p.get(f + '_reason')))} |"
            )
        if p.get("other_notes"):
            L += ["", f"Notes: {_one(p['other_notes'])}"]
        L += [
            "",
            "Owner checklist: [ ] definition  [ ] template  [ ] examples  [ ] near-misses  (accept / edit / reject)",
            "",
        ]
    L += [
        "## Decisions for the owner",
        "",
        "1. Wording of each relation above (accept / edit / reject).",
        "2. measured_by and evaluated_by: keep both (A), merge (B) or drop evaluated_by (C).",
        "3. Whether the `evaluation` family belongs in the textbook registry at all.",
        "4. Only then: adopt v1.4 (needs new relation prompt versions, a re-run, and the CR-022 Part B decision).",
    ]
    return "\n".join(L) + "\n"


def main() -> str:
    reg = yaml.safe_load(V14.read_text(encoding="utf-8"))
    prop = yaml.safe_load(PROPOSALS.read_text(encoding="utf-8"))
    sha = hashlib.sha256(V14.read_bytes()).hexdigest()
    text = render(reg, prop, sha)
    OUT.write_text(text, encoding="utf-8")
    assert hashlib.sha256(V14.read_bytes()).hexdigest() == sha  # v1.4 is never edited
    return text


if __name__ == "__main__":
    main()
    print(f"wrote {Path(OUT).relative_to(REPO_ROOT)}")
