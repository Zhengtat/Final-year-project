"""CR-031 ($0, no model call): the SciNLP oracle ladder (E0 / E1 / E3-M / E4-M) re-scored under the CR-019 groundings.

    uv run python -m cumap.cr031.oracle_ladder

Read-only on the frozen CR-012 held-out runs (their checkpoint hashes are recorded before and after). Reports the
`FROZEN` figure beside every rescored variant (rule 35) and writes only `reports/cr031/`. These are test-split figures
computed for reporting only (rule 9)."""

from __future__ import annotations

import collections as C
import hashlib
import json
from collections.abc import Callable
from pathlib import Path

from cumap.config import REPO_ROOT
from cumap.cr012 import production_graph as PG
from cumap.cr012 import scinlp_run as SR
from cumap.cr012 import scoring as S
from cumap.cr012.adapters import SciNLPAdapter
from cumap.cr012.stop4_score import sc_attribution
from cumap.cr019 import variants as V
from cumap.cr019.run import SC_DOCS, sc_run_id

OUT = REPO_ROOT / "reports/cr031"
LEVELS = ("E0", "E1", "E3", "E4")  # E3 / E4 are the SciNLP E3-M / E4-M runs (surface pseudo-nodes)
LEVEL_LABEL = {"E0": "E0", "E1": "E1", "E3": "E3-M", "E4": "E4-M"}
VARIANTS = ("FROZEN", "IDX-P1", "IDXR1-P1", "IDX-P3")
CODES = ("N0", "N1", "P0", "R0", "R1", "recovered")


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def ladder(
    doc_keys: list[str] = SC_DOCS,
    levels: tuple[str, ...] = LEVELS,
    variants: tuple[str, ...] = VARIANTS,
    *,
    docs: dict | None = None,
    gold_all: dict | None = None,
    sym: set[str] | None = None,
    load_run: Callable[[str], dict] = PG.load_run,
    run_path: Callable[[str], Path] = PG.run_path,
    score: Callable = V.sc_score,
    attribution: Callable = sc_attribution,
) -> dict:
    """Read-only rescoring. The loaders and scorers are injectable so a fixture can drive it."""
    if docs is None or gold_all is None or sym is None:
        ad = SciNLPAdapter()
        gold_all, sym = ad.gold("test"), ad.symmetric_relations()
        docs = {d.doc_key: d for d in ad.load_documents("test", paragraph_every=SR.PARAGRAPH_EVERY)}
    paths = [run_path(sc_run_id(dk, lv)) / "checkpoint.json" for dk in doc_keys for lv in levels]
    before = {str(p): _sha(p) for p in paths if p.exists()}
    out: dict = {}
    for lv in levels:
        for v in variants:
            per: dict = {}
            codes: C.Counter = C.Counter()
            predicted = unplaced = 0
            for dk in doc_keys:
                cp = load_run(sc_run_id(dk, lv))
                r = score(docs[dk], gold_all[dk], cp, sym, v)
                per[dk] = r["scores"]
                predicted += r["edges"]["predicted"]
                unplaced += r["edges"]["unplaced"]
                codes.update(
                    c or "recovered"
                    for c in attribution(docs[dk], gold_all[dk], r["pred"], cp, sym)
                )
            out[f"{lv}/{v}"] = {
                "rel": S.aggregate_documents(per, "rel")["micro"],
                "entity_strict": S.aggregate_documents(per, "entity_strict")["micro"],
                "predicted_edges": predicted,
                "unplaced_edges": unplaced,
                "earliest_failure": dict(codes),
            }
    after = {str(p): _sha(p) for p in paths if p.exists()}
    out["sources_unchanged"] = before == after
    out["source_hashes"] = after
    return out


def _f(x) -> float:
    return x.f1 if hasattr(x, "f1") else x["f1"]


def _g(x, k: str) -> float:
    return getattr(x, k) if hasattr(x, k) else x[k]


def render_md(res: dict, levels: tuple[str, ...] = LEVELS) -> str:
    """Generated text only: tables from `res`, no claim that is not a number in it."""
    L = [
        "# CR-031 SciNLP oracle ladder under the CR-019 groundings",
        "",
        (
            "Generated by `cumap.cr031.oracle_ladder` ($0, no model call). Test split, computed for reporting only "
            "(rule 9). Each rescored figure sits beside the `FROZEN` CR-012 figure (rule 35)."
        ),
        "",
        f"Source checkpoints unchanged by the run: **{res['sources_unchanged']}**.",
        "",
        "## Relation strict F1 (P / R) by level and grounding variant",
        "",
        "| Level | "
        + " | ".join(VARIANTS)
        + " | entity strict F1 FROZEN / IDX-P1 | predicted / unplaced edges (IDX-P1) |",
        "|---|" + "---|" * (len(VARIANTS) + 2),
    ]
    for lv in levels:
        cells = []
        for v in VARIANTS:
            r = res.get(f"{lv}/{v}")
            cells.append(
                "n/a"
                if r is None
                else f"{_f(r['rel']):.3f} ({_g(r['rel'], 'precision'):.3f} / {_g(r['rel'], 'recall'):.3f})"
            )
        e0, e1 = res.get(f"{lv}/FROZEN"), res.get(f"{lv}/IDX-P1")
        ent = (
            f"{_f(e0['entity_strict']):.3f} / {_f(e1['entity_strict']):.3f}" if e0 and e1 else "n/a"
        )
        pe = f"{e1['predicted_edges']} / {e1['unplaced_edges']}" if e1 else "n/a"
        L.append(f"| {LEVEL_LABEL.get(lv, lv)} | " + " | ".join(cells) + f" | {ent} | {pe} |")
    L += [
        "",
        "## Earliest-failure codes under `IDX-P1` (gold relations)",
        "",
        "`right fact, not credited` = `recovered` minus strict true positives (inferred).",
        "",
        "| Level | " + " | ".join(CODES) + " | strict TP | right fact, not credited |",
        "|---|" + "---|" * (len(CODES) + 2),
    ]
    for lv in levels:
        r = res.get(f"{lv}/IDX-P1")
        if r is None:
            continue
        c = r["earliest_failure"]
        tp = _g(r["rel"], "tp")
        L.append(
            f"| {LEVEL_LABEL.get(lv, lv)} | "
            + " | ".join(str(c.get(k, 0)) for k in CODES)
            + f" | {tp} | {c.get('recovered', 0) - tp} |"
        )
    steps = []

    def f(lv: str, v: str):
        return _f(res[f"{lv}/{v}"]["rel"]) if f"{lv}/{v}" in res else None

    for a, b, name in (
        ("E0", "E1", "concept step E0 to E1"),
        ("E1", "E3", "pair delivery E1 to E3-M"),
    ):
        for v in ("FROZEN", "IDX-P1"):
            x, y = f(a, v), f(b, v)
            if x is not None and y is not None:
                steps.append(f"- {name}, `{v}`: {y - x:+.3f}")
    if steps:
        L += ["", "## Steps between levels (strict relation F1)", "", *steps]
    return "\n".join(L) + "\n"


def to_jsonable(res: dict) -> dict:
    def conv(x):
        if hasattr(x, "to_dict"):
            return x.to_dict()
        if isinstance(x, dict):
            return {k: conv(v) for k, v in x.items()}
        return x

    return conv(res)


def main() -> dict:
    res = ladder()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "oracle_ladder.json").write_text(
        json.dumps(to_jsonable(res), indent=1, default=str), encoding="utf-8"
    )
    (OUT / "oracle_ladder.md").write_text(render_md(res), encoding="utf-8")
    return res


if __name__ == "__main__":
    r = main()
    print(render_md(r))
