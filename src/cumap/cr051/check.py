"""CR-051 confirmation (not a gate; the owner chose sol): the adopted rejected-link adjudicator v2 on the tier the policy now names
(`escalate` = gpt-6-sol under the luna profile), on the owner's fresh CR-050 sheet, beside the CR-050 luna numbers.

    uv run python -m cumap.cr051.check --dry-run | --limit 20 | (all)
    uv run python -m cumap.cr051.check --score      # reports/cr051/adjudicator_sol.{json,md}"""

from __future__ import annotations

import argparse
import json

from cumap.concepts_v4.rejected_links import AdjudicationLLM, adjudicator_tier
from cumap.config import REPO_ROOT, get_settings
from cumap.cr021 import adjudicator as A
from cumap.cr050 import measure as M50
from cumap.gold.validate import verify_quote

RUN_ID = "cr051_adjudicator_sol"
OUT = REPO_ROOT / "reports" / "cr051"
RESULTS = OUT / "results.jsonl"  # local only (gitignored): reasons can quote CC BY-NC SciNLP text
CAP_USD = 1.0


def _done() -> dict[str, dict]:
    return (
        {x["key"]: x for x in map(json.loads, RESULTS.read_text().splitlines())}
        if RESULTS.exists()
        else {}
    )


def run(*, dry_run: bool, limit: int | None) -> dict:
    from cumap.llm.client import LLMClient
    from cumap.llm.cost import spend_from_log
    from cumap.llm.prompts import load_prompt

    st = get_settings()
    tier = adjudicator_tier(st.llm.tiers)
    rows = M50.load_rows()[:limit] if limit else M50.load_rows()
    todo = [r for r in rows if r["key"] not in _done()]
    if dry_run:
        return {
            "dry_run": True,
            "tier": tier,
            "model": st.llm.tiers[tier].model,
            "calls": len(todo),
            "est_usd": round(len(todo) * 0.002, 3),
        }
    if spend_from_log(st, RUN_ID) >= CAP_USD:
        raise SystemExit(f"CR-051 cap reached: ${CAP_USD}")
    client = LLMClient(st, run_id=RUN_ID)
    p = load_prompt(REPO_ROOT / "prompts", "rejected_link_adjudicator", "v2")
    OUT.mkdir(parents=True, exist_ok=True)
    with RESULTS.open("a", encoding="utf-8") as f:
        for r in todo:
            inp = M50.render_inputs(r)
            res = client.parse(task="rejected_link_adjudicator", prompt_version=p.version, messages=[{"role": "user", "content": p.render(**inp)}],
                               schema=AdjudicationLLM, model_tier=tier)  # fmt: skip
            o = res.output
            dec = o.decision if verify_quote(o.evidence_quote, inp["evidence"]) else "no_decision"
            f.write(
                json.dumps(
                    {
                        "key": r["key"],
                        "decision": dec,
                        "raw": o.decision,
                        "reason": o.reason,
                        "model": res.model if hasattr(res, "model") else None,
                    }
                )
                + "\n"
            )
    return {
        "calls": len(todo),
        "spend_usd": round(client.spent_usd, 4),
        "total_usd": round(spend_from_log(st, RUN_ID), 4),
    }


def score() -> dict:
    from cumap.llm.cost import spend_from_log

    rows, got = M50.load_rows(), _done()
    sc = A.score(rows, got, "fresh")
    sc["accuracy"] = sum(r["gold"] == got[r["key"]]["decision"] for r in rows) / len(rows)
    luna = json.loads((M50.OUT / "judge_v1.json").read_text())["arms"]
    out = {
        "rows": len(rows),
        "sol": sc,
        "luna_cr050": {k: luna[k] for k in ("ADJ", "J1")},
        "spend_usd": round(spend_from_log(get_settings(), RUN_ID), 4),
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "adjudicator_sol.json").write_text(
        json.dumps(out, indent=1, default=str), encoding="utf-8"
    )
    f = M50._f
    L = ["# CR-051: the rejected-link adjudicator v2 on sol, fresh owner sheet (confirmation, not a gate)", "",
         "Generated by `cumap.cr051.check --score` ($0). Same 103 owner-marked rows and inputs as CR-050.", "",
         "| judge | accuracy | new_concept P (LB) | same P (LB) | gold same rows decided new |", "|---|---|---|---|---|"]  # fmt: skip
    for name, s in (
        ("ADJ on sol (CR-051)", sc),
        ("ADJ on luna (CR-050)", luna["ADJ"]),
        ("J1 on luna (CR-050)", luna["J1"]),
    ):
        pn, ps = s["precision_new_concept"], s["precision_same_as_target"]
        L.append(f"| {name} | {f(s['accuracy'])} | {pn['correct']}/{pn['decided']} = {f(pn['precision'])} ({f(pn['wilson_lb'])}) | {ps['correct']}/{ps['decided']} = {f(ps['precision'])} ({f(ps['wilson_lb'])}) | {s['same_rows_decided_new']['count']}/{s['same_rows_decided_new']['of']} |")  # fmt: skip
    L += ["", f"Sol confusion: {sc['confusion']}", "", f"Spend: ${out['spend_usd']}.", ""]
    (OUT / "adjudicator_sol.md").write_text("\n".join(L), encoding="utf-8")
    return {
        "accuracy": sc["accuracy"],
        "same": sc["precision_same_as_target"],
        "new": sc["precision_new_concept"],
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--limit", type=int)
    ap.add_argument("--score", action="store_true")
    a = ap.parse_args()
    print(
        json.dumps(
            score() if a.score else run(dry_run=a.dry_run, limit=a.limit), indent=1, default=str
        )
    )


if __name__ == "__main__":
    main()
