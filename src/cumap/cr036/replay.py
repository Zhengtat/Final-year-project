"""CR-036 ($0, no model call): what `assembly: v2` would do to a saved run. Read-only; writes only `reports/cr036/`.

    uv run python -m cumap.cr036.replay [--run slice3_c2]

Builds the v2 edge store from the run's classification results and compares it with the legacy assembly (the checkpoint's pair registry and chapter
snapshots), and counts the domain/range rejections that "direction from types" would recover."""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter

from cumap.config import REPO_ROOT, get_settings
from cumap.expert_kg import edge_store as ES
from cumap.schemas.relations import RelationRegistry

OUT = REPO_ROOT / "reports/cr036"
KG = REPO_ROOT / "data/processed/kg"


def legacy_edges(run: str) -> set[tuple[str, str, str]]:
    out = set()
    for f in sorted((KG / run / "snapshots").glob("ch*/edges.jsonl")):
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.strip():
                e = json.loads(line)
                out.add((e["source_concept_id"], e["relation"], e["target_concept_id"]))
    return out


def replay(cp: dict, registry: RelationRegistry, legacy: set[tuple[str, str, str]]) -> dict:
    types = {c["concept_id"]: c["node_type"] for c in cp["concepts"]}
    store = ES.build_edge_store(cp["relation_results_v3"], types, registry)
    v2 = {(e.source_id, e.relation, e.target_id) for e in store.edges}
    ev = Counter(x["event"] for x in store.log)
    selected_edges = [r for r in cp["relation_results_v3"] if r.get("outcome") == "edge" and r.get("group", "selected") == "selected" and not r.get("gated_dropped")]  # fmt: skip
    return {
        "legacy_snapshot_edges": len(legacy),
        "v2_store_edges": len(store.edges),
        "edges_in_both": len(v2 & legacy),
        "only_in_legacy": sorted(legacy - v2)[:10],
        "only_in_v2": sorted(v2 - legacy)[:10],
        "selected_edge_results": len(selected_edges),
        "direction_set_by_types_in_stored_edges": ev.get("direction_set_by_types", 0),
        "merged_identical": ev.get("merged_into", 0),
        "relation_not_in_registry": ev.get("relation_not_in_registry", 0),
        "conflicts_flagged": len(store.conflicts),
        "flags": dict(Counter(f for e in store.edges for f in e.flags)),
        "measurement_sample_results": len(store.measurement),
        "second_relation_on_a_pair": sum(1 for e in store.edges if "~" in e.edge_id),
        "domain_range": ES.recoverable_domain_range(cp["relation_results_v3"], types, registry),
        "run_records_a_registry_version": bool((cp.get("selection_stats") or {}).get("registry")),
    }


def markdown(run: str, reg_label: str, r: dict, unchanged: bool) -> str:
    dr = r["domain_range"]
    L = [
        f"# CR-036 `assembly: v2` $0 replay on `{run}` (registry {reg_label})",
        "",
        f"Generated by `cumap.cr036.replay`. Read-only; source hashes identical before and after: **{unchanged}**. `assembly: v2` is NOT adopted (default `legacy`); no model call. Nothing in the run was changed: this shows what the v2 edge store would hold.",
        "",
        f"- selected edge results in the run: **{r['selected_edge_results']}**; legacy snapshot edges: **{r['legacy_snapshot_edges']}**; v2 edge store: **{r['v2_store_edges']}** (in both: {r['edges_in_both']})",
        f"- only in legacy: {r['only_in_legacy']}; only in v2: {r['only_in_v2']}",
        f"- stored edges whose direction `v2` sets from node types (model's answer was type-invalid): **{r['direction_set_by_types_in_stored_edges']}**",
        f"- identical edges merged: **{r['merged_identical']}**; second relation on a pair: **{r['second_relation_on_a_pair']}**; conflicts flagged: **{r['conflicts_flagged']}**; relation not in the loaded registry (skipped): **{r['relation_not_in_registry']}**",
        f"- measurement-sample results kept out of the edge store: **{r['measurement_sample_results']}**",
        f"- classification-time `domain_range` rejections: **{dr['domain_range_rejections']}**; of these the OTHER orientation is type-valid for **{dr['recoverable_by_direction_from_types']}** (`v2` would store that edge, flagged `direction_set_by_types`, instead of rejecting it). Examples: {dr['examples'][:5]}",
        f"- the run records a registry version: **{r['run_records_a_registry_version']}** (a run without a record is refused by `v2` and must be assembled with `legacy`)",
        "",
        "The owner decides (beside the domain/range owner review) whether recovered edges are right: the model's own statement describes the orientation it chose.",
    ]
    return "\n".join(L) + "\n"


def main(run: str = "slice3_c2") -> dict:
    cp_path = KG / run / "checkpoint.json"
    snaps = sorted((KG / run / "snapshots").glob("ch*/edges.jsonl"))
    files = [cp_path, *snaps]
    before = {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
    cp = json.loads(cp_path.read_text(encoding="utf-8"))
    reg = RelationRegistry.from_yaml(REPO_ROOT / get_settings().relation_registry)
    r = replay(cp, reg, legacy_edges(run))
    unchanged = before == {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"assembly_replay_{run}.json").write_text(
        json.dumps({"run": run, "registry": reg.version_label, **r}, indent=1, default=str),
        encoding="utf-8",
    )
    (OUT / f"assembly_replay_{run}.md").write_text(
        markdown(run, reg.version_label, r, unchanged), encoding="utf-8"
    )
    print(
        {k: v for k, v in r.items() if k not in ("domain_range",)},
        r["domain_range"]["recoverable_by_direction_from_types"],
    )
    return r


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="slice3_c2")
    main(ap.parse_args().run)
