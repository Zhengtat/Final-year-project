"""CR-034 ($0, no model call): replay of the qualifier code checks on a saved run. Read-only; writes only `reports/cr034/`.

    uv run python -m cumap.cr034.replay [--run slice3_c2]

Counts, per check, which edges of the run the checks (`qualifier_checks: v1`) would flag or reject. Nothing in the run is changed."""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter

from cumap.config import REPO_ROOT, get_settings
from cumap.expert_kg import qualifier_checks as QC
from cumap.schemas.relations import RelationRegistry

OUT = REPO_ROOT / "reports/cr034"


def replay(cp: dict, registry: RelationRegistry) -> dict:
    edges = [r for r in cp["relation_results_v3"] if r["outcome"] == "edge"]
    by_check: Counter = Counter()
    examples: dict[str, list[dict]] = {}
    flagged = rejected = 0
    for r in edges:
        flags = QC.check_edge(
            registry, r["relation"], r.get("qualifiers") or {}, r.get("evidence_quote")
        )
        if not flags:
            continue
        flagged += 1
        if QC.REJECT_REASON in flags:
            rejected += 1
        for f in flags:
            by_check[f] += 1
            ex = examples.setdefault(f, [])
            if len(ex) < 5:
                ex.append(
                    {
                        "pair_id": r["pair"]["pair_id"],
                        "section": r["pair"]["section_id"],
                        "relation": r["relation"],
                        "quote": r.get("evidence_quote"),
                        "surface_phrase": (r.get("qualifiers") or {}).get("surface_phrase"),
                        "polarity": (r.get("qualifiers") or {}).get("polarity"),
                    }
                )
    negated = [r for r in edges if (r.get("qualifiers") or {}).get("polarity") == "negated"]
    return {
        "edges": len(edges),
        "edges_with_any_flag": flagged,
        "edges_rejected_under_v1": rejected,
        "negated_edges": len(negated),
        "negated_with_cue": sum(QC.has_negation_cue(r.get("evidence_quote")) for r in negated),
        "by_check": dict(sorted(by_check.items())),
        "examples": examples,
    }


def markdown(run: str, reg_version: str, res: dict, unchanged: bool) -> str:
    L = [
        f"# CR-034 qualifier checks, $0 replay on `{run}` (registry {reg_version})",
        "",
        (
            "Generated by `cumap.cr034.replay`. Read-only: no edge was changed or removed; this counts what `qualifier_checks: v1` would do to a NEW classification of the same edges. "
            f"Source checkpoint hash identical before and after: **{unchanged}**."
        ),
        "",
        f"- edges in the run: **{res['edges']}**; edges with at least one flag: **{res['edges_with_any_flag']}**",
        f"- edges that `v1` would REJECT (`negation_without_cue`, owner default D-4): **{res['edges_rejected_under_v1']}** of {res['negated_edges']} negated edges ({res['negated_with_cue']} have a negation cue)",
        "",
        "| check | edges it would flag |",
        "|---|---|",
        *[f"| `{k}` | {v} |" for k, v in res["by_check"].items()],
        "",
        "`qualifier_misfit:*` and `surface_phrase_long` are recorded as flags only (they do not reject): the old prompt versions produce them on many edges, and a later prompt version (CR-038) is what removes them.",
        "",
        "## Examples (up to 5 per check)",
    ]
    for k, ex in res["examples"].items():
        L += ["", f"### `{k}`", ""]
        for e in ex:
            L.append(
                f"- {e['pair_id']} ({e['section']}), `{e['relation']}`, polarity {e['polarity']}: quote “{e['quote']}”; surface phrase “{e['surface_phrase']}”"
            )
    return "\n".join(L) + "\n"


def main(run: str = "slice3_c2") -> dict:
    path = REPO_ROOT / "data/processed/kg" / run / "checkpoint.json"
    before = hashlib.sha256(path.read_bytes()).hexdigest()
    cp = json.loads(path.read_text(encoding="utf-8"))
    reg = RelationRegistry.from_yaml(REPO_ROOT / get_settings().relation_registry)
    res = replay(cp, reg)
    unchanged = before == hashlib.sha256(path.read_bytes()).hexdigest()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"qualifier_replay_{run}.json").write_text(
        json.dumps({"run": run, "registry": reg.version_label, **res}, indent=1), encoding="utf-8"
    )
    (OUT / f"qualifier_replay_{run}.md").write_text(
        markdown(run, reg.version_label, res, unchanged), encoding="utf-8"
    )
    print({k: v for k, v in res.items() if k != "examples"})
    return res


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="slice3_c2")
    main(ap.parse_args().run)
