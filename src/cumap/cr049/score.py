"""CR-049 scoring ($0): ADJ vs J1 vs J2 on the CR-021 dev and held-out rows (held-out = second look) and the lexicon `different` stress set.
Applies the rule pre-registered in docs/DECISIONS.md. Writes reports/cr049/identity_judge.{json,md}."""

from __future__ import annotations

import json
from collections import Counter

from cumap.cr021 import adjudicator as A
from cumap.cr049 import measure as M

MARGIN = 0.03


def arm_scores(split: str, res: dict) -> dict:
    rows = M.rows(split)
    out = {}
    for arm in M.ARMS:
        got = {k: x for (a, k), x in res.items() if a == arm}
        if all(r["key"] in got for r in rows):
            sc = A.score(rows, got, split)
            sc["accuracy"] = sum(r["gold"] == got[r["key"]]["decision"] for r in rows) / len(rows)
            if arm != "ADJ":
                sc["judge_answers"] = dict(
                    Counter(got[r["key"]].get("judge_decision") for r in rows)
                )
            out[arm] = sc
    return out


def stress(res: dict) -> dict:
    items = M.stress_items()
    out = {}
    for arm in M.ARMS:
        got = [res.get((arm, i["key"])) for i in items]
        if all(got):
            out[arm] = {"items": len(items), "decided_same": sum(x["decision"] == "same_as_target" for x in got),
                        "same_pairs": [f"{i['surface']} / {i['rejected_target']}" for i, x in zip(items, got, strict=True) if x["decision"] == "same_as_target"]}  # fmt: skip
    return out


def decide(h: dict) -> dict:
    if not {"ADJ", "J2"} <= h.keys():
        return {"status": "NOT_SCORED"}
    j, a = h["J2"], h["ADJ"]
    p_j, p_a = (
        j["precision_same_as_target"]["precision"],
        a["precision_same_as_target"]["precision"],
    )
    lb_new, lb_same = (
        j["precision_new_concept"]["wilson_lb"],
        j["precision_same_as_target"]["wilson_lb"],
    )
    srn = j["same_rows_decided_new"]
    share = srn["count"] / srn["of"] if srn["of"] else 0.0
    ok = p_j is not None and p_a is not None and p_j >= p_a - MARGIN and (lb_new or 0) >= 0.70 and (lb_same or 0) >= 0.70 and share <= 0.20  # fmt: skip
    return {
        "status": "J2_PASSES" if ok else "KEEP_ADJ",
        "j2_same_precision": p_j, "adj_same_precision": p_a, "j2_new_concept_wilson_lb": lb_new, "j2_same_wilson_lb": lb_same,
        "j2_same_rows_decided_new_share": share,
        "rule": "held-out (second look): J2 same precision >= ADJ same precision - 0.03, J2 new_concept and same Wilson LB >= 0.70, at most 20% of gold same rows decided new_concept",
    }  # fmt: skip


def main() -> dict:
    res = M.load_results()
    out = {
        "dev": arm_scores("dev", res),
        "heldout": arm_scores("heldout", res),
        "stress": stress(res),
    }
    out["decision"] = decide(out["heldout"])
    from cumap.config import get_settings
    from cumap.llm.cost import spend_from_log

    out["spend_usd"] = round(spend_from_log(get_settings(), M.RUN_ID), 4)
    M.OUT.mkdir(parents=True, exist_ok=True)
    (M.OUT / "identity_judge.json").write_text(
        json.dumps(out, indent=1, default=str), encoding="utf-8"
    )
    (M.OUT / "identity_judge.md").write_text(markdown(out), encoding="utf-8")
    return out["decision"]


def _f(x) -> str:
    return "—" if x is None else f"{x:.3f}"


def markdown(r: dict) -> str:
    L = [
        "# CR-049: identity judge v2 (GraphJudge elements) against the adjudicator v2 and judge v1",
        "",
        ("Generated by `cumap.cr049.score` ($0). Rows: the owner-checked CR-021 sheet (model-assisted labels), fixed dev / held-out split, SciNLP test "
         "rows left out (rule 9). **Held-out is a second look** (it decided the CR-021 adoption). Same rows and model profile (luna) for every arm."),
        "",
    ]  # fmt: skip
    d = r["decision"]
    if d.get("status") != "NOT_SCORED":
        L += [(f"**Decision ({d['rule']}): {d['status']}.** J2 same precision {_f(d['j2_same_precision'])} vs ADJ {_f(d['adj_same_precision'])}; "
              f"J2 Wilson LB new {_f(d['j2_new_concept_wilson_lb'])}, same {_f(d['j2_same_wilson_lb'])}; gold-same rows decided new {d['j2_same_rows_decided_new_share']:.3f}."), ""]  # fmt: skip
    for split in ("dev", "heldout"):
        L += [
            f"## {split}",
            "",
            "| arm | accuracy | new_concept P (LB) | same P (LB) | not_a_concept P | same rows decided new |",
            "|---|---|---|---|---|---|",
        ]
        for arm, s in r[split].items():
            pn, ps, pc = (
                s["precision_new_concept"],
                s["precision_same_as_target"],
                s["precision_not_a_concept"],
            )
            L.append(f"| {arm} | {_f(s['accuracy'])} | {pn['correct']}/{pn['decided']} = {_f(pn['precision'])} ({_f(pn['wilson_lb'])}) | {ps['correct']}/{ps['decided']} = {_f(ps['precision'])} ({_f(ps['wilson_lb'])}) | {pc['correct']}/{pc['decided']} | {s['same_rows_decided_new']['count']}/{s['same_rows_decided_new']['of']} |")  # fmt: skip
        L += [""] + [f"- {arm} confusion: {s['confusion']}" + (f"; judge answers {s['judge_answers']}" if "judge_answers" in s else "") for arm, s in r[split].items()] + [""]  # fmt: skip
    L += ["## Stress set: approved lexicon `different` pairs (a `same` is a false merge)", ""]
    L += [
        f"- {arm}: {s['decided_same']} / {s['items']} decided same {s['same_pairs']}"
        for arm, s in r["stress"].items()
    ]
    L += ["", f"Spend: ${r['spend_usd']} of ${M.CAP_USD}.", ""]
    return "\n".join(L)
